// Exercício 2: Converter Letras para Maiúsculas
// Enunciado:
// Peça ao usuário que digite uma frase ou palavra. Depois, exiba o texto com
// todas as letras em maiúsculas

let userInput = prompt("Digite uma frase ou palavra, irei converter para maiúsculo: ")

inputConvertido = userInput.toUpperCase

alert(`Sua frase convertida: ${inputConvertido}`)